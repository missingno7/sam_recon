"""Build Sam Port Console, a CP437 subset/resampling of GNU Unifont 14.0.01.
No DOS ROM/game data is read. The pinned upstream release is the only input.
Run with --download to fetch it; regeneration thereafter works offline.
"""
import argparse
from pathlib import Path
import urllib.request

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "port" / "pc" / "font-source"
URL = "https://raw.githubusercontent.com/deepin-community/unifont/6134ebc549827ebc1c831b5ee219282ef0052d3c/font/plane00/unifont-base.hex"
CONTROLS = [0,0x263a,0x263b,0x2665,0x2666,0x2663,0x2660,0x2022,0x25d8,
            0x25cb,0x25d9,0x2642,0x2640,0x266a,0x266b,0x263c,0x25ba,0x25c4,
            0x2195,0x203c,0xb6,0xa7,0x25ac,0x21a8,0x2191,0x2193,0x2192,0x2190,
            0x221f,0x2194,0x25b2,0x25bc]

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--download", action="store_true")
    args = ap.parse_args()
    SOURCE.mkdir(exist_ok=True)
    if args.download:
        urllib.request.urlretrieve(URL, SOURCE / "unifont-base.hex")
    fontname = SOURCE / "unifont-base.hex"
    if not fontname.exists():
        fontname = SOURCE / "cp437.hex"
    hexdata = fontname.read_text(encoding="ascii")
    glyphs = {int(k,16):bytes.fromhex(v) for k,v in (line.split(":") for line in hexdata.splitlines())}
    rows = []
    for c in range(256):
        cp = CONTROLS[c] if c<32 else 0x2302 if c==127 else ord(bytes([c]).decode("cp437"))
        assert cp in glyphs or cp in (32,160), (c,cp)
        bits = bytes(16) if c==0 else glyphs.get(cp,bytes(16))
        if len(bits)==32:
            # Area reduction from fullwidth Unicode glyph to eight columns.
            bits=bytes(sum((1<<(7-x)) for x in range(8) if int.from_bytes(bits[2*y:2*y+2],"big") & (3<<(14-2*x))) for y in range(16))
        assert len(bits)==16, (c,cp)
        rows.append(bits)
    dest=ROOT/"port"/"pc"
    text="/* Sam Port Console, derived from GNU Unifont 14.0.01; SIL OFL 1.1.\n   Generated by tools/make_fonts.py; see fonts-LICENSE.txt. */\n"
    text+="#include <stdint.h>\nstatic const uint8_t font16[256][16] = {\n"
    text+="\n".join("    {"+",".join(f"0x{x:02x}" for x in bits)+"}," for bits in rows)+"\n};\n"
    (dest/"font_data.h").write_text(text,encoding="ascii")
    print("Generated 256 CP437 glyphs from",fontname)

if __name__=="__main__": main()
