"""Re-derive every claim from committed inputs.

    python tools/validate.py [--fresh] [--write-progress] [--only FUNCTION ...]

  * the oracle matches its immutable lock (tools/oracle.py);
  * the census/atlas and data layout regenerate to the committed files;
  * every recipe's routine is re-proven: each episode the recipe claims EQUAL must
    still be EQUAL (compiles come from the content-addressed cache unless --fresh);
  * accepted sources agree on declarations: one declaration text per global, and a
    callee's stub header matches the accepted routine's own header;
  * --write-progress regenerates docs/progress.md.
"""
from __future__ import annotations

import argparse
import re
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from common import EPISODES, EVIDENCE, LAYOUT, RECIPES, ROOT, SRC, load_json  # noqa: E402
import harness  # noqa: E402
import search  # noqa: E402


def norm(s: str) -> str:
    return re.sub(r"\s+", " ", s.strip().rstrip(";")).lower()


def signature(header: str) -> str:
    """Kind, parameter modes/types and result type of a header; parameter names dropped."""
    h = norm(header)
    m = re.match(r"(procedure|function)\s+\w+\s*(?:\((.*)\))?\s*(?::\s*(.*))?$", h)
    if not m:
        return h
    params = []
    for group in filter(None, (g.strip() for g in (m.group(2) or "").split(";"))):
        mode = ""
        g = group
        for kw in ("var ", "const "):
            if g.startswith(kw):
                mode, g = kw.strip(), g[len(kw):]
        names, _, typ = g.partition(":")
        params += [f"{mode} {typ.strip()}".strip()] * len(names.split(","))
    return f"{m.group(1)}({', '.join(params)}){': ' + m.group(3).strip() if m.group(3) else ''}"


def declarations() -> list:
    """Conflicting global declarations / stub headers among accepted sources."""
    globs, heads, own = {}, {}, {}
    for p in sorted((SRC / "routines").glob("*.pas")):
        text = p.read_text(encoding="latin-1")
        sec = harness.split_sections(text)
        d = harness.parse_decls(sec["decls"])
        for n, decl in d.globals.items():
            globs.setdefault(n, {}).setdefault(norm(decl.split(":", 1)[1].split("=")[0]), []).append(p.stem)
        for n, h in harness.parse_stubs(sec["stubs"]):
            heads.setdefault(n, {}).setdefault(signature(h), []).append(p.stem)
        if re.match(r"(?is)^\s*begin\b", harness._strip_comments(sec["body"]).strip()):
            continue            # INIT/MAIN body: no header of its own
        tgt = harness.target_name(sec["body"])
        m = re.search(r"(?ims)^\s*((?:procedure|function)\s+" + re.escape(tgt) + r"\b[^;]*(?:\([^)]*\))?[^;]*;)",
                      harness._strip_comments(sec["body"]))
        if m:
            own[tgt] = signature(m.group(1))
    problems = []
    for n, views in globs.items():
        if len(views) > 1:
            problems.append(f"global {n}: " + " | ".join(f"{t} ({', '.join(v)})" for t, v in views.items()))
    for n, views in heads.items():
        allv = set(views) | ({own[n]} if n in own else set())
        if len(allv) > 1:
            problems.append(f"header {n}: " + " | ".join(sorted(allv)))
    return problems


def regen_check() -> list:
    out = []
    for cmd in (["tools/oracle.py"], ["tools/census.py"], ["tools/atlas.py", "--check"]):
        r = subprocess.run([sys.executable, *cmd], cwd=ROOT, capture_output=True, text=True)
        if r.returncode != 0:
            out.append(f"{' '.join(cmd)} failed: {(r.stdout + r.stderr).strip().splitlines()[-1:]}")
    return out


def progress(results: dict) -> str:
    atlas = load_json(EVIDENCE / "atlas.json")
    rs = atlas["routines"]
    by_unit = {}
    for lid, r in rs.items():
        u = by_unit.setdefault(r["unit"], {"n": 0, "bytes": 0, "acc": 0, "acc_bytes": 0})
        u["n"] += 1
        u["bytes"] += r["size"]
        if lid in results and results[lid]["ok"]:
            u["acc"] += 1
            u["acc_bytes"] += r["size"]
    lines = ["# Progress", "", "Regenerated by `python tools/validate.py --write-progress`.", "",
             "| Unit | Routines | Accepted | Bytes | Accepted bytes |", "|---|---:|---:|---:|---:|"]
    tot = [0, 0, 0, 0]
    for u in atlas["units"]:
        x = by_unit.get(u)
        if not x:
            continue
        lines.append(f"| {u} | {x['n']} | {x['acc']} | {x['bytes']} | {x['acc_bytes']} |")
        for i, k in enumerate(("n", "acc", "bytes", "acc_bytes")):
            tot[i] += x[k]
    lines.append(f"| **total** | {tot[0]} | {tot[1]} | {tot[2]} | {tot[3]} |")
    lines += ["", "Borland runtime units (crt, dos, sys) come from the pinned TURBO.TPL and are proven by",
              "the whole-program build, not routine by routine.", ""]
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--fresh", action="store_true")
    ap.add_argument("--write-progress", action="store_true")
    ap.add_argument("--only", nargs="*")
    ap.add_argument("--program", action="store_true", help="also run the whole-program proof (tools/finalcheck.py)")
    ap.add_argument("--standalone", action="store_true", help="also build game/ standalone and compare (tools/standalone.py)")
    a = ap.parse_args()
    failures = regen_check() if not a.only else []
    results = {}
    _, options = search.profile_options(None)
    for rp in sorted(RECIPES.glob("*.json")):
        rec = load_json(rp)
        f = rec["function"]
        if a.only and f not in a.only:
            continue
        text = (ROOT / rec["source"]).read_text(encoding="latin-1")
        ok = True
        if rec.get("kind") == "asm":
            import asmproof
            for p in asmproof.prove_source(text, rec["unit"], rec["equal"]):
                if p.status != "EQUAL":
                    ok = False
                    failures.append(f"{f} {p.episode}: {p.short()}")
            results[f] = {"ok": ok}
            for c in rec.get("covers", []):
                results[c] = {"ok": ok}
            print(f"{f}: {'OK' if ok else 'REGRESSED'} ({','.join(rec['equal'])}, assembly)")
            continue
        for ep in rec["equal"]:
            res, _ = search.run_episode(text, f, ep, search.profile_options(rec["profile"])[1], a.fresh)
            if res.status != "EQUAL":
                ok = False
                failures.append(f"{f} {ep}: {res.short()}")
        results[f] = {"ok": ok}
        for c in rec.get("covers", []):
            results[c] = {"ok": ok}
        print(f"{f}: {'OK' if ok else 'REGRESSED'} ({','.join(rec['equal'])})")
    if a.program:
        r = subprocess.run([sys.executable, str(ROOT / "tools" / "finalcheck.py")], cwd=ROOT)
        if r.returncode != 0:
            failures.append("whole-program proof (tools/finalcheck.py) failed")
    if a.standalone:
        r = subprocess.run([sys.executable, str(ROOT / "tools" / "standalone.py"), str(ROOT / "game")], cwd=ROOT)
        if r.returncode != 0:
            failures.append("standalone build of game/ (tools/standalone.py) failed")
    decl = declarations()
    for p in decl:
        print("DECLARATION " + p)
    if a.write_progress:
        (ROOT / "docs" / "progress.md").write_text(progress(results), encoding="utf-8")
    for f in failures:
        print("FAIL " + f)
    print(f"{sum(1 for r in results.values() if r['ok'])}/{len(results)} recipes re-proven, "
          f"{len(decl)} declaration conflicts, {len(failures)} failures")
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
